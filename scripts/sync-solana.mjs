#!/usr/bin/env node
/**
 * Regenerate the two Solana files the `@rally-fun/sdk/solana` entry point is built on:
 *
 *   src/solana/idl.generated.ts         the rally_solana_protocol IDL, trimmed to what the SDK uses
 *   src/solana/deployments.generated.ts the baked Solana deploy manifests
 *
 * Sources (both owned by packages/rally-solana, never edited from here):
 *
 *   packages/rally-solana/idl/rally_solana_protocol.json
 *   packages/rally-solana/deployments/<chainId>.json     (written by deploy-devnet.sh)
 *
 * The IDL is trimmed, not copied: instruction names, discriminators, argument layouts
 * and account lists (order, writable/signer/optional flags, fixed addresses) for every
 * instruction, the account layouts the read helpers decode, and the defined types those
 * reach. Events, errors and docs are dropped, so the bundle does not grow with them. The
 * encoders and decoders in `codec.ts` are driven by this file, so a layout change in the
 * program re-flows by regenerating instead of by hand-copying.
 *
 * A manifest is baked only when it exists and names a `RallySolanaProtocol`. Nothing is invented
 * for a cluster the program has not been deployed to: the record is simply empty.
 *
 * `--check` regenerates in memory and compares, exiting non-zero on drift. Run by
 * `check:deployments`, so `prepublishOnly` cannot ship a stale program id or layout.
 *
 *   node scripts/sync-solana.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const solanaDir = resolve(here, "../../rally-solana");
const idlPath = join(solanaDir, "idl/rally_solana_protocol.json");
const manifestDir = join(solanaDir, "deployments");
const outIdl = resolve(here, "../src/solana/idl.generated.ts");
const outDeployments = resolve(here, "../src/solana/deployments.generated.ts");
const checkOnly = process.argv.includes("--check");

/** Envio HyperSync label ids, the Solana "chain id" everywhere in Rally (docs/SOLANA.md). */
const SOLANA_CHAIN_IDS = [7565164, 7565165];

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascalToCamel = (s) => s.charAt(0).toLowerCase() + s.slice(1);

// ── IDL ──────────────────────────────────────────────────────────────────────

const idl = JSON.parse(readFileSync(idlPath, "utf8"));
const typesByName = new Map(idl.types.map((t) => [t.name, t]));

const needed = new Set();
const reach = (ty) => {
  if (typeof ty === "string") return;
  if (ty.defined) {
    const name = ty.defined.name;
    if (needed.has(name)) return;
    needed.add(name);
    const def = typesByName.get(name);
    if (!def) throw new Error(`IDL references undefined type ${name}`);
    if (def.type.kind === "struct") def.type.fields.forEach((f) => reach(f.type));
    return;
  }
  if (ty.vec) return reach(ty.vec);
  if (ty.option) return reach(ty.option);
  if (ty.array) return reach(ty.array[0]);
  throw new Error(`unsupported IDL type ${JSON.stringify(ty)}`);
};

const instructions = idl.instructions.map((ix) => {
  ix.args.forEach((a) => reach(a.type));
  return {
    name: ix.name,
    discriminator: ix.discriminator,
    accounts: ix.accounts.map((a) => {
      const o = { name: a.name };
      if (a.writable) o.writable = true;
      if (a.signer) o.signer = true;
      if (a.optional) o.optional = true;
      if (a.address) o.address = a.address;
      return o;
    }),
    args: ix.args.map((a) => ({ name: a.name, type: a.type })),
  };
});

const accounts = idl.accounts
  // Only accounts that have a layout in `types` and that the read helpers decode.
  .filter((a) => ["Config", "Launch", "QuoteConfig", "ReferralAccount"].includes(a.name))
  .map((a) => {
    reach({ defined: { name: a.name } });
    return { name: a.name, discriminator: a.discriminator };
  });

const types = [...needed].sort().map((name) => {
  const def = typesByName.get(name);
  return def.type.kind === "struct"
    ? { name, kind: "struct", fields: def.type.fields.map((f) => ({ name: f.name, type: f.type })) }
    : { name, kind: "enum", variants: def.type.variants.map((v) => v.name) };
});

// Discriminators and `{name,type}` leaves read better inline; the rest keeps its indent.
const compact = (json) =>
  json
    .replace(/\[\s*((?:\d+,\s*)*\d+)\s*\]/g, (_, nums) => `[${nums.replace(/\s+/g, " ")}]`)
    .replace(/\{\s*("name": "[^"]*"),\s*("type": "[^"]*")\s*\}/g, "{ $1, $2 }");

const idlFile = `// GENERATED by scripts/sync-solana.mjs — do not edit by hand.
// Source: packages/rally-solana/idl/rally_solana_protocol.json (trimmed: see the script header).
// Regenerate after any program change, then publish a new SDK version.

export const RALLY_SOLANA_PROTOCOL_IDL = ${compact(
  JSON.stringify({ address: idl.address, instructions, accounts, types }, null, 2),
)} as const;
`;

// ── Deployments ──────────────────────────────────────────────────────────────

const entries = [];
for (const id of SOLANA_CHAIN_IDS) {
  const p = join(manifestDir, `${id}.json`);
  if (!existsSync(p)) continue;
  const m = JSON.parse(readFileSync(p, "utf8"));
  if (!m.RallySolanaProtocol) {
    console.warn(`  skipping chain ${id}: manifest has no RallySolanaProtocol (deploy never completed)`);
    continue;
  }
  // The manifest's `Quotes[]` row shape is owned by the deploy script; keys are carried
  // through camelCased rather than re-modelled here, so a field it adds is not dropped.
  const quotes = (Array.isArray(m.Quotes) ? m.Quotes : []).map((q) =>
    Object.fromEntries(Object.entries(q).map(([k, v]) => [pascalToCamel(k), v])),
  );
  entries.push([
    id,
    {
      vm: "svm",
      chainId: id,
      caip2: m.Caip2,
      rallySolanaProtocol: m.RallySolanaProtocol,
      config: m.Config,
      lookupTable: m.LookupTable,
      raydiumClmm: m.RaydiumClmm,
      raydiumAmmConfig: m.RaydiumAmmConfig,
      quotes,
    },
  ]);
}

const body = entries
  .map(([id, d]) => `  ${id}: ${JSON.stringify(d, null, 2).replace(/\n/g, "\n  ")},`)
  .join("\n");

const deploymentsFile = `// GENERATED by scripts/sync-solana.mjs — do not edit by hand.
// Source: packages/rally-solana/deployments/<chainId>.json (written by deploy-devnet.sh).
// Empty until the program is deployed to a cluster. Regenerate after every redeploy.
import type { SolanaDeployment } from "./types";

export const SOLANA_DEPLOYMENTS: Record<number, SolanaDeployment> = {
${body}
};
`;

// ── Write / check ────────────────────────────────────────────────────────────

const chains = entries.map(([c]) => c).join(", ") || "none";
if (checkOnly) {
  const stale = [];
  if (readFileSync(outIdl, "utf8") !== idlFile) stale.push("src/solana/idl.generated.ts");
  if (readFileSync(outDeployments, "utf8") !== deploymentsFile) stale.push("src/solana/deployments.generated.ts");
  if (stale.length) {
    console.error(
      `${stale.join(", ")} stale against packages/rally-solana.\n` +
        `Run \`yarn workspace @rally-fun/sdk sync:solana\`, review the diff, and bump the version.`,
    );
    process.exit(1);
  }
  console.log(`solana files are current (deployed chains: ${chains})`);
} else {
  writeFileSync(outIdl, idlFile);
  writeFileSync(outDeployments, deploymentsFile);
  console.log(`Wrote solana IDL and deployments (deployed chains: ${chains})`);
}
